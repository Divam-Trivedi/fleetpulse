-- Run as ACCOUNTADMIN in a Snowsight worksheet.
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS FLEETPULSE;
CREATE SCHEMA IF NOT EXISTS FLEETPULSE.RAW;

-- Small warehouse that suspends fast, with a hard credit cap.
CREATE WAREHOUSE IF NOT EXISTS FLEETPULSE_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS FLEETPULSE_RM
  WITH CREDIT_QUOTA = 5
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE FLEETPULSE_WH SET RESOURCE_MONITOR = FLEETPULSE_RM;

-- Requires the IAM role from `terraform apply` #1 to exist.
CREATE STORAGE INTEGRATION IF NOT EXISTS FLEETPULSE_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::859934688085:role/fleetpulse-snowflake-role'
  STORAGE_ALLOWED_LOCATIONS = ('s3://fleetpulse-raw-859934688085-us-west-2/raw/telemetry/');

-- Copy STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID into terraform.tfvars
DESC INTEGRATION FLEETPULSE_S3_INT;
