-- Least-privilege role for Snowpark work. Run once as ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS FLEETPULSE_DEV;
SET me = CURRENT_USER();
GRANT ROLE FLEETPULSE_DEV TO USER IDENTIFIER($me);

GRANT USAGE ON WAREHOUSE FLEETPULSE_WH TO ROLE FLEETPULSE_DEV;
GRANT USAGE ON DATABASE FLEETPULSE     TO ROLE FLEETPULSE_DEV;

-- ML schema: features, labels, models, predictions live here and are owned by the dev role.
CREATE SCHEMA IF NOT EXISTS FLEETPULSE.ML;
GRANT ALL PRIVILEGES ON SCHEMA FLEETPULSE.ML TO ROLE FLEETPULSE_DEV;

-- Read access to upstream layers, including objects created later or re-created.
GRANT USAGE ON SCHEMA FLEETPULSE.RAW     TO ROLE FLEETPULSE_DEV;
GRANT USAGE ON SCHEMA FLEETPULSE.STAGING TO ROLE FLEETPULSE_DEV;
GRANT USAGE ON SCHEMA FLEETPULSE.MARTS   TO ROLE FLEETPULSE_DEV;

GRANT SELECT ON ALL TABLES          IN SCHEMA FLEETPULSE.RAW     TO ROLE FLEETPULSE_DEV;
GRANT SELECT ON ALL DYNAMIC TABLES  IN SCHEMA FLEETPULSE.STAGING TO ROLE FLEETPULSE_DEV;
GRANT SELECT ON ALL DYNAMIC TABLES  IN SCHEMA FLEETPULSE.MARTS   TO ROLE FLEETPULSE_DEV;
GRANT SELECT ON ALL VIEWS           IN SCHEMA FLEETPULSE.MARTS   TO ROLE FLEETPULSE_DEV;

GRANT SELECT ON FUTURE TABLES         IN SCHEMA FLEETPULSE.RAW     TO ROLE FLEETPULSE_DEV;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FLEETPULSE.STAGING TO ROLE FLEETPULSE_DEV;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FLEETPULSE.MARTS   TO ROLE FLEETPULSE_DEV;
GRANT SELECT ON FUTURE VIEWS          IN SCHEMA FLEETPULSE.MARTS   TO ROLE FLEETPULSE_DEV;

-- Sanity check
USE ROLE FLEETPULSE_DEV;
USE WAREHOUSE FLEETPULSE_WH;
SELECT COUNT(*) FROM FLEETPULSE.STAGING.STG_TELEMETRY;
