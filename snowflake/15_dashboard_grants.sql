-- What the dashboard's FLEETPULSE_DEV role needs beyond reading data: the alert log, pause/resume, pipe status.
USE ROLE ACCOUNTADMIN;

GRANT SELECT  ON TABLE FLEETPULSE.ML.ALERT_LOG TO ROLE FLEETPULSE_DEV;
GRANT OPERATE ON WAREHOUSE FLEETPULSE_WH       TO ROLE FLEETPULSE_DEV;

GRANT OPERATE ON ALL DYNAMIC TABLES    IN SCHEMA FLEETPULSE.STAGING TO ROLE FLEETPULSE_DEV;
GRANT OPERATE ON ALL DYNAMIC TABLES    IN SCHEMA FLEETPULSE.MARTS   TO ROLE FLEETPULSE_DEV;
GRANT OPERATE ON ALL DYNAMIC TABLES    IN SCHEMA FLEETPULSE.ML      TO ROLE FLEETPULSE_DEV;
GRANT OPERATE ON FUTURE DYNAMIC TABLES IN SCHEMA FLEETPULSE.STAGING TO ROLE FLEETPULSE_DEV;   -- survives CREATE OR REPLACE
GRANT OPERATE ON FUTURE DYNAMIC TABLES IN SCHEMA FLEETPULSE.MARTS   TO ROLE FLEETPULSE_DEV;
GRANT OPERATE ON FUTURE DYNAMIC TABLES IN SCHEMA FLEETPULSE.ML      TO ROLE FLEETPULSE_DEV;

-- Snowflake does not allow ALL / FUTURE grants on pipes, so grant per pipe. Re-run after recreating a pipe.
